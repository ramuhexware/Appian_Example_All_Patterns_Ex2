package com.appian.enterprise.employee.soap.model;

import jakarta.xml.bind.annotation.XmlAccessType;
import jakarta.xml.bind.annotation.XmlAccessorType;
import jakarta.xml.bind.annotation.XmlElement;
import jakarta.xml.bind.annotation.XmlRootElement;

import java.math.BigDecimal;

@XmlRootElement(name = "SoapEmployeeResponse", namespace = "http://soap.employee.enterprise.appian.com/")
@XmlAccessorType(XmlAccessType.FIELD)
public class SoapEmployeeResponse {

    @XmlElement
    private String employeeId;

    @XmlElement
    private String fullName;

    @XmlElement
    private String email;

    @XmlElement
    private String title;

    @XmlElement
    private BigDecimal salary;

    @XmlElement
    private String status;

    @XmlElement
    private String responseCode;

    public SoapEmployeeResponse() {}

    public String getEmployeeId() {
        return employeeId;
    }

    public void setEmployeeId(String employeeId) {
        this.employeeId = employeeId;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public BigDecimal getSalary() {
        return salary;
    }

    public void setSalary(BigDecimal salary) {
        this.salary = salary;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getResponseCode() {
        return responseCode;
    }

    public void setResponseCode(String responseCode) {
        this.responseCode = responseCode;
    }
}
